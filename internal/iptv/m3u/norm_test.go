package m3u

import "testing"

// Нормализация названий для сопоставления с каналами телепрограммы (спека этапа 8, раздел 5.3):
// регистр, «ё», пометки в скобках и метки качества не различают канал; сдвиг «+N» — различает и
// пишется одинаково.
func TestNorm(t *testing.T) {
	cases := map[string]string{
		"Первый канал HD":              "первый канал",
		"ПЕРВЫЙ КАНАЛ":                 "первый канал",
		"Первый канал +4":              "первый канал +4",
		"Первый канал (+4)":            "первый канал +4",
		"Первый канал + 4 HD":          "первый канал +4",
		"Россия 1 (+6)":                "россия 1 +6",
		"Мир +7 (Архив)":               "мир +7",
		"2x2 (576i)":                   "2x2",
		"Нано ТВ (480p) [Not 24/7]":    "нано тв",
		"Arsenal (720p) [Geo-blocked]": "arsenal",
		"Пятница!":                     "пятница",
		"Ёлки ТВ":                      "елки тв",
		"Canal+ Sport":                 "canal+ sport",
		"Матч! Футбол 1 50 fps":        "матч футбол 1",
		"Матч! Футбол 1 50fps":         "матч футбол 1",
		"GLN 24 (Геленджик)":           "gln 24 геленджик",
		" 4K UHD релакс":               "релакс",
		"Звезда orig":                  "звезда",
		"ТНТ4":                         "тнт4",
		"Россия 1 (2)":                 "россия 1", // номер дубля в плейлисте
		"Россия 24 +0 (Липецк)":        "россия 24 липецк",
		"Первый канал (12)":            "первый канал",
		"Канал (2024)":                 "канал 2024",
		"Россия 24 + 0":                "россия 24",
	}
	for in, want := range cases {
		if got := Norm(in); got != want {
			t.Errorf("Norm(%q) = %q, нужно %q", in, got, want)
		}
	}
}

func TestSplitShift(t *testing.T) {
	cases := []struct {
		in    string
		base  string
		shift int
	}{
		{"первый канал +4", "первый канал", 4},
		{"россия 1 +6", "россия 1", 6},
		{"первый канал", "первый канал", 0},
		{"canal+ sport", "canal+ sport", 0},
		{"канал +12", "канал +12", 0}, // сдвиг — от 1 до 9 часов (спека, раздел 5.3)
		{"+4", "+4", 0},
	}
	for _, c := range cases {
		base, shift := SplitShift(c.in)
		if base != c.base || shift != c.shift {
			t.Errorf("SplitShift(%q) = %q, %d; нужно %q, %d", c.in, base, shift, c.base, c.shift)
		}
	}
}

// WithoutPlace — последняя пометка в скобках, обычно город региональной вставки: «Россия 24 +0 (Липецк)» →
// «Россия 24 +0». Без скобок — как было.
func TestWithoutPlace(t *testing.T) {
	cases := map[string]string{
		"Россия 24 +0 (Липецк)":       "Россия 24 +0",
		"Россия 1 (+7) (Владивосток)": "Россия 1 (+7)",
		"GLN 24":               "GLN 24",
		"Первый канал (+4)":    "Первый канал (+4)", // сдвиг — не место
		"Россия 1 (Москва) HD": "Россия 1 (Москва) HD",
	}
	for in, want := range cases {
		if got := WithoutPlace(in); got != want {
			t.Errorf("WithoutPlace(%q) = %q, нужно %q", in, got, want)
		}
	}
}
